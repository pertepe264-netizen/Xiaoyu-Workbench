# -*- coding: utf-8 -*-
"""
👨‍🏫 班长 H3 注意力加速节点

让 MiniMax-H3 生成得更快：注意力只重点算真正重要的部分，画质基本不变。
内部用的是 ComfyUI 官方 comfy-kitchen 的 sol-attn 内核（自适应挑块：画面
复杂的地方多留、简单的地方少留）；显卡或环境不支持时自动回退到自带的
Triton 内核，节点照常工作。

MiniMax-H3 走的是官方那条「块级替换」路子：QKV 每 4096 个 token 现算一小片
直接喂内核，完整 QKV 从头到尾不存在。比"先把完整 QKV 算出来再稀疏"省掉约
1.9 GB 显存（47135 长度实测 2.40G vs 4.28G），在大分辨率 / 分块放大时不容易
顶到显存上限，加速也就不会忽有忽无。

接在 MODEL 线上：放在 LoRA 加载器之后、采样器之前即可。
分辨率 / 时长越高，提速越明显。

「画面多长才值得加速」由节点首次使用时在本机实测一次并缓存，不用手填。
运行报告只打印在后台控制台（不看也不影响出图）。
"""

import logging

log = logging.getLogger("BanzhangSLA")

BLOCK_SIZES = ("64", "128")


class BanZhang_SLABlockSparseAttention:
    """H3 注意力加速：让每个画面块只去看跟它最相关的那部分画面。

    画面被切成很多小块，每块先用很便宜的方式给其他块打个分，只留下分数高的
    那些真正算。这里没有任何需要额外加载的东西，也不改模型权重。
    """

    DESCRIPTION = (
        "让 MiniMax-H3 生成得更快：只重点计算真正重要的部分，画质基本不变。\n"
        "分辨率 / 时长越高，提速越明显。接在 LoRA 加载器之后、采样器之前即可。\n"
        "\n【怎么调】\n"
        "· 想更快 → 把「省多少计算」调大\n"
        "· 想找回细节 → 把「省多少计算」调小，或把「最后几步精修」调大\n"
        "· 构图跑偏 → 把「开头几步不省」调大\n"
        "· 带声音 → 「保住声音」一定要开着\n"
        "\n【默认值已对齐 ComfyUI 官方节点】（省 90 = 官方 tau 1.3）。\n"
        "没有专用加速 LoRA 的话，先试 85 更稳妥。\n"
        "「画面太短就不加速」是节点内部固定判断，不需要你设置。"
    )

    @classmethod
    def INPUT_TYPES(cls):
        return {
            "required": {
                "模型": ("MODEL",),
                "省多少计算": (
                    "INT",
                    {
                        "default": 95,
                        "min": 0,
                        "max": 95,
                        "step": 5,
                        "tooltip": (
                            "决定生成快多少。数字越大越快，画面细节越容易掉一点。\n"
                            "· 90（默认）：和 ComfyUI 官方节点的默认档一致\n"
                            "· 85：更保守，画质几乎看不出变化\n"
                            "· 95：最快，只在赶时间时用\n"
                            "· 0：完全不加速（等于把这个节点关掉）\n"
                            "拿不准就停在 90；觉得画面糙了往下调，觉得慢往上调。"
                        ),
                    },
                ),
                "开头几步不省": (
                    "INT",
                    {
                        "default": 0,
                        "min": 0,
                        "max": 8,
                        "tooltip": (
                            "开头这几步决定整个画面的构图和人物长相，让它们完整算，\n"
                            "后面再省，画面会稳很多（官方默认让开头 20% 的步不省）。\n"
                            "· 1（默认）：第 1 步完整算\n"
                            "· 0：从头就省，最快，构图偶有跑偏\n"
                            "· 2~3：步数多（8 步以上）时可以加\n"
                            "注意：总共只有 3~4 步时，建议把它或「最后几步精修」关掉一个，\n"
                            "否则真正省到的只剩一步，加速就没意义了。"
                        ),
                    },
                ),
                "最后几步精修": (
                    "INT",
                    {
                        "default": 0,
                        "min": 0,
                        "max": 8,
                        "tooltip": (
                            "让最后几步用完整计算收尾，画面更稳更细，代价是慢一点。\n"
                            "· 1（默认）：最后一步完整算；官方默认是 0，\n"
                            "  但开着能让后台日志算出「加速到底省了多少时间」\n"
                            "· 0：全程加速，最快（跟官方默认一致）\n"
                            "· 2~3：追求画质时开"
                        ),
                    },
                ),
                "保住声音": (
                    "BOOLEAN",
                    {
                        # 默认开：带声音的生成几乎不花额外时间，关掉却可能让人声/配乐变怪，
                        # 收益极小、风险不小。这里必须与 apply_sla 签名里的默认值一致
                        # （曾出现界面 False / 签名 True 的错配，拖出来的节点默认是关的）。
                        "default": True,
                        "tooltip": (
                            "额外保护声音部分，避免出现「画面正常但配乐 / 人声变怪」。\n"
                            "带声音一定要开着（几乎不花时间）。\n"
                            "关掉只会快一点点，不推荐。"
                        ),
                    },
                ),
                "参考声音保多少": (
                    "INT",
                    {
                        "default": 64,
                        "min": 0,
                        "max": 65536,
                        "step": 512,
                        "tooltip": (
                            "只管「参考素材」（关键帧 / 参考视频）带来的声音。\n"
                            "你要生成的声音是一直完整保护的，调这个不会伤到它。\n"
                            "· 0（默认）：只保要生成的声音，最快\n"
                            "· 8192：参考素材里的声音也很重要时再调大\n"
                            "一般保持 0 不动。\n"
                            "注：走官方分片内核时，视频之前的整段（含参考声音）本就\n"
                            "完整保护，这一项只在回退到自带内核时才起作用。"
                        ),
                    },
                ),
                "计算块大小": (
                    BLOCK_SIZES,
                    {
                        "default": "64",
                        "tooltip": (
                            "通常不用动。\n"
                            "官方分片内核固定按 64 分块，这一项只在回退到自带内核时\n"
                            "才有区别：64 声音更自然，128 更快但人声可能发僵。"
                        ),
                    },
                ),
            },
        }

    RETURN_TYPES = ("MODEL",)
    FUNCTION = "apply_sla"
    CATEGORY = "👨‍🏫班长/模型优化"

    def apply_sla(
        self,
        模型,
        省多少计算=95,
        开头几步不省=0,
        最后几步精修=0,
        保住声音=True,
        参考声音保多少=64,
        计算块大小="64",
    ):
        try:
            from .sla import patch_h3_sla

            patched = patch_h3_sla(
                模型,
                sparsity_ratio=省多少计算 / 100.0,
                block_size=int(计算块大小),
                min_seq_len=0,          # 保留位：内部已改用固定安全下限，不再自动标定
                dense_first_steps=开头几步不省,
                dense_last_steps=最后几步精修,
                protect_audio=保住声音,
                protect_cap=参考声音保多少,
            )
        except Exception:
            # Triton 缺失、GPU 不兼容、ComfyUI API 变更 —— 都不该让用户这次运行失败，
            # 不加速的注意力仍然可用。
            log.exception(
                "[班长SLA] 加速补丁没挂上，这次按不加速跑（不影响出图）。"
            )
            return (模型,)

        return (patched,)


