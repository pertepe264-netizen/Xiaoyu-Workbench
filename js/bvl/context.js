/**
 * 共享抽屉（ctx）：一个节点实例的全部运行状态 + 各模块互相调用的函数入口。
 *
 * 各功能块（滑条 / 工具行 / 去重 / 多选 / 网格 / 卡片 / 列表…）都从这一个对象上取东西，
 * 彼此不互相 import —— 想改哪个功能，读那一个文件 + 本文件的字段表就够了。
 *
 * 字段分三类：
 *   1. 静态引用：节点、控件、容器等 DOM / 节点对象
 *   2. 运行状态：卡片列表、筛选条件、多选集合等
 *   3. 函数入口：由各模块创建时注入（标了「谁注入」）
 */

export function 创建上下文({ node, 文件夹控件, 文件控件, 排序控件, 尺寸控件, 子目录控件, 容器, 提示层 }) {
    return {
        // ---- 静态引用 ----
        node,
        文件夹控件,
        文件控件,
        排序控件,
        尺寸控件,
        子目录控件,
        容器,                       // 网格滚动容器 .bz-grid-container
        提示层,                     // 「松手上传」提示层，清空容器时要留着
        当前路径: () => (文件夹控件.value || "").replace(/["']/g, ""),

        // ---- 运行状态 ----
        缓存的卡片列表: [],
        当前列数: 0,
        防抖定时器: null,
        过滤关键字: "",
        类型筛选: "all",
        多选模式: false,
        已选集合: new Set(),
        上次多选卡片: null,
        刷新令牌: 0,
        缓存列表已失效: true,
        // 当前列表相对 ComfyUI input 目录的前缀："" = 就在 input 根，"子目录/" = 在
        // input 的子目录里。null = 列表不在 input 目录内，拖拽只能走字节投放。
        // 由 list_images 的 X-Input-Rel 响应头给出（后端算，前端不算路径）。
        输入相对前缀: null,
        缩略图观察器: null,
        计数: null,                 // 筛选行右侧的命中计数元素（筛选行模块放入）

        // ---- 函数入口（由各模块注入，调用时都已就位）----
        记住路径: () => {},         // 工具行模块
        同步滑条: () => {},         // 滑条模块
        排队重排: () => {},         // 滑条模块
        回读尺寸: () => 60,         // 滑条模块
        打开去重: () => {},         // 去重模块
        关闭去重: () => {},         // 去重模块
        同步递归钮: () => {},       // 筛选行模块
        同步多选条: () => {},       // 多选模块
        清空多选: () => {},         // 多选模块
        多选点击: () => {},         // 多选模块
        显示匹配: () => true,       // 网格模块
        重排布局: () => {},         // 网格模块
        请求重排: () => {},         // 网格模块
        挂载懒加载: () => {},       // 网格模块
        隐藏预览: () => {},         // 悬停预览模块
        显示预览: () => {},         // 悬停预览模块
        跟随预览: () => {},         // 悬停预览模块
        开始播放: () => {},         // 播放模块
        停止播放: () => {},         // 播放模块
        停止全部播放: () => {},     // 播放模块
        排期播放: () => {},         // 播放模块
        取消排期播放: () => {},     // 播放模块
        加载媒体列表: () => {},     // 列表模块
        触发刷新: () => {},         // 列表模块
        更新选中状态: () => {},     // 列表模块
    };
}
